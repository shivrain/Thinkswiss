sub("(3)  Plans shall prioritise: direct contribution to economic development and poverty reduction; productive and quick-return activities; improvement of living standards, income and employment; maximising local participation and volunteerism; optimal use of local resources and skills; direct benefit to women, children and disadvantaged groups; gender equality and social inclusion; sustainable development and environmental protection; and promotion of linguistic and cultural aspects and social harmony.")
sub("(4)  Plans shall include a list of medium and long-term projects.")
sub("(5)  Planning and implementation shall involve maximum participation of local intellectuals, subject experts, experienced professionals, marginalised and endangered communities, women, children, Dalits, youth, minorities, persons with disabilities, senior citizens and other stakeholders.")
sub("(6)  Planning shall include resource estimation based on feasibility studies; project prioritisation; implementation schedules; and monitoring and evaluation plans.")
sub("(7)  When the Government of Nepal or Provincial Government provides grants for special programmes and prescribes implementation procedures, local authorities shall follow those procedures.")
sub("(8)  Local authorities may operate and manage plans in joint investment or public-private partnership with federal or provincial governments.")
sub("(9)  Local authorities shall coordinate, facilitate and cooperate in implementing federal and provincial level projects.")
sub("(10)  Local authorities may conduct necessary studies, research and impact assessments of local development projects.")

sec(25, "Working in Coordination")
sub("(1)  NGOs, consumer committees, cooperatives and other social/community organisations shall work in coordination with local authorities.")
sub("(Proviso)  International NGOs working in coordination with local authorities shall have prior approval from the Government of Nepal.")
sub("(2)  When coordinating with local authorities, such organisations shall: conduct studies/surveys/programmes based on agreements with the local authority; include their annual plans, programmes and budgets in the local authority's plans; and follow joint monitoring and progress reporting systems as prescribed by the local authority.")
sub("(3)  If any organisation acts contrary to this section, the local authority may stop such activities.")
sub("(4)  Other coordination provisions shall be pursuant to local law.")

sec(26, "Partnership or Joint Management")
