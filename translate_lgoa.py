chapter("CHAPTER 12 — PROVISIONS RELATING TO THE DISTRICT ASSEMBLY")
# ══════════════════════════════════════════════════════════════════════════════
sec(92, "Functions, Duties and Rights of the District Assembly")
sub("(1)  In addition to functions specified in Article 220(7) of the Constitution, the District Assembly's further functions, duties and rights shall include:")
item("a", "Identify development/construction matters among Village Municipalities and Municipalities in the district and coordinate necessary management.")
item("b", "Prepare details of development/construction programmes operated by governmental and non-governmental sectors across the district; monitor effectiveness and management; provide recommendations and guidance to maintain sectoral/community/environmental balance in programme outcomes; make such recommendations public.")
item("c", "Coordinate with the Federal and Provincial Governments for capacity development of local authorities in the district.")
item("d", "Coordinate between federal/provincial government offices in the district and Village Municipalities/Municipalities.")
item("e", "Coordinate and facilitate resolution if a dispute arises between Village Municipalities/Municipalities in the district.")
item("f", "Coordinate disaster management plans and work across the district.")
item("g", "Coordinate with NGOs and the private sector to maintain balance in district development and construction work.")
item("h", "Study, research and monitor balance in development/construction work; provide suggestions to the Ministry, provincial ministry and relevant local authorities.")
item("i", "Report to the Ministry and provincial ministry on its work within two months of each fiscal year's end.")
item("j", "Organise at least one annual review programme per year and invite Members of Parliament representing the district for suggestions.")
item("k", "Carry out other tasks designated by the Government of Nepal or Provincial Government.")
sub("(2)  The work of the District Assembly shall be in the name of the District Coordination Committee.")
sub("(3)  The District Assembly shall prepare annual programmes and budgets, pass them through the District Assembly and implement them.")
sub("(4)  The District Assembly may prepare necessary procedures, guidelines and standards in its jurisdiction.")

sec(93, "Budget of the District Assembly")
sub("(1)  The Government of Nepal and Provincial Government shall provide necessary budgets to the District Assembly.")
sub("(2)  Such amounts and other income shall be deposited in the District Assembly's fund.")
sub("(3)  Allowances for District Coordination Committee members shall be paid from this budget.")

sec(94, "District Coordination Officer and Staff")
sub("(1)  The District Assembly shall have a District Coordination Officer as its administrative head.")
sub("(2)  The District Coordination Officer's functions include: acting as Secretary of the District Assembly and Committee; implementing Committee decisions; coordinating federal/provincial offices and local authorities; maintaining financial accounts; protecting District Assembly property; convening meetings; procurement planning; and other assigned tasks.")
sub("(3)  The Government of Nepal shall depute a civil servant as District Coordination Officer.")
sub("(4)–(8)  The District Coordination Committee shall prepare staffing proposals for permanent and contract positions based on an organisational management survey; ensure financial resources for all service benefits; not create temporary posts; fill vehicle driver, watchman, plumber, electrician and cleaning positions by competitive service contract only; not fill other positions by contract.")

sec(95, "Coordination with the District Assembly")
body("Government of Nepal and Provincial Government offices located in the district shall work in coordination with the District Coordination Committee.")

sec(96, "Meetings of the District Assembly and District Coordination Committee")
sub("(1)  The District Assembly shall meet at least once a year; the District Coordination Committee at least once a month.")
sub("(2)  The District Coordination Committee Chairperson shall convene meetings.")
sub("(3)  Meetings shall be chaired by the District Coordination Committee Chairperson; in absence, by the Vice-Chairperson; if also absent, by the senior-most member present.")
sub("(4)  More than fifty percent of sitting members constitutes a quorum.")
sub("(5)  Decisions shall be by consensus; if not possible, by majority; in a tie, the presiding person casts the deciding vote.")

