chapter("CHAPTER 8 — JUDICIAL FUNCTIONS")
# ══════════════════════════════════════════════════════════════════════════════
sec(46, "Judicial Committee")
body("Each Village Municipality and Municipality shall have a Judicial Committee pursuant to Article 217 of the Constitution.")

sec(47, "Jurisdiction of the Judicial Committee")
sub("(1)  The Judicial Committee shall have authority to adjudicate the following disputes:")
item("a", "Distribution and use of ridges, embankments, canals, water channels and water mills.")
item("b", "Crop damage to another's field.")
item("c", "Grazing land, grass and firewood.")
item("d", "Non-payment of wages.")
item("e", "Loss or finding of domestic animals.")
item("f", "Failure to maintain and care for senior citizens.")
item("g", "Failure to provide reasonable food, clothing or education to minor children or spouses.")
item("h", "House rental and related benefits up to Rs 2.5 million per year.")
item("i", "Planting trees and plants that affect another person's house, land or property.")
item("j", "Draining water from one's house or roof onto another's house, land or public road.")
item("k", "Building a house facing a neighbour's land without leaving the legally required setback.")
item("l", "Preventing use of or obstructing paths, passages, grazing land, canals, ponds, rest houses, cremation grounds, religious places and other public spaces that have been used traditionally.")
item("m", "Other disputes designated by federal or provincial law for adjudication by local authorities.")
sub("(2)  The Judicial Committee shall have authority to resolve the following disputes through mediation only:")
item("a", "Encroachment or occupation of another's private land (other than government, public or community land).")
item("b", "Construction of a house or structure on another's private land without authorisation.")
item("c", "Divorce between spouses (however, mediation cannot result in forced divorce).")
item("d", "Physical assault punishable by up to one year's imprisonment (excluding disfigurement).")
item("e", "Verbal abuse and insult.")
item("f", "Robbery and looting.")
item("g", "Leaving animals unattended or negligent animal husbandry that affects others.")
item("h", "Unauthorised entry into another's dwelling.")
item("i", "Tilling or occupying another's land without authorisation.")
item("j", "Causing harm to a neighbour through noise pollution or throwing waste.")
item("k", "Other civil disputes filed by a plaintiff eligible for mediation, and criminal disputes punishable by up to one year's imprisonment, under prevailing law.")
sub("(3)  Notwithstanding sub-section (2), a party may always file a case in court.")
sub("(4)  Applications for the disputes listed must be filed within the limitation period set in prevailing law, or within thirty-five days of the event if no limitation is prescribed.")

sec(48, "Exercise of Jurisdiction")
sub("(1)  The Judicial Committee shall exercise jurisdiction collectively (Convenor + members), with majority opinion as the decision.")
sub("(2)  The Convenor and at least one other member present suffices to conduct and decide proceedings.")
sub("(3)  If the Convenor is absent and two other members are present, proceedings (other than final decisions) may continue.")
sub("(4)–(7)  Provisions for conflict of interest, recusal and replacement of members who cannot hear certain disputes.")
note("Members with personal interest or whose relatives are parties shall be recused; the Assembly shall appoint three alternative members for such disputes.")

sec(49, "Judicial Process")
sub("(1)  The Judicial Committee shall register disputes and provide copies of the registration to parties.")
sub("(2)  The Committee shall encourage and facilitate mediation, and both parties shall try to reach a mediated settlement. If not possible, for disputes under Section 47(1), the Committee shall adjudicate pursuant to law.")
sub("(3)  Mediation shall be conducted by mediators registered by the Judicial Committee.")
sub("(4)  The Committee shall resolve disputes by mediation within three months of both parties appearing. If mediation fails, for disputes under Section 47(2), the Committee shall inform parties and forward documents to court.")
sub("(5)–(7)  The Judicial Committee may also freeze bank accounts, deposits or immovable property assets of respondents upon application, and may lift such freezes on application.")
sub("(8)  In marital or senior citizen protection disputes, the Committee may issue interim protective orders: ordering the accused to allow the victim to remain in the home; providing medical treatment; arranging separate accommodation with maintenance; prohibiting verbal/physical abuse; and other appropriate protective measures.")
sub("(9)  Respondents shall appear before the Judicial Committee within the prescribed period or within fifteen days (plus travel time) of the filing.")
sub("(10)  The Judicial Committee may establish mediation centres in each ward.")
sub("(12)  Procedures for registration, hearings, service of process, mediation, time limits and other judicial functions shall be pursuant to local law.")

sec(50, "Written Notification of Decision")
body("A certified copy of the Judicial Committee's final decision shall be provided to the relevant parties within thirty-five days of the decision.")

sec(51, "Right to Appeal")
body("A party dissatisfied with a Judicial Committee decision may appeal to the relevant District Court within thirty-five days of learning of the decision.")

sec(52, "Implementation of Settlement or Decision")
sub("(1)  The Executive shall immediately implement (and cause to implement) settlements or decisions of the Judicial Committee.")
sub("(2)  Other provisions regarding implementation shall be pursuant to local law.")

sec(53, "Maintenance of Records")
sub("(1)  The local authority shall maintain orderly and secure records of all documents, settlements and decisions relating to cases resolved by the Judicial Committee.")
sub("(2)  The Judicial Committee shall present an annual report of its work to the relevant Assembly through the Chairperson/Mayor.")

