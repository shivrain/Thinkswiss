sec(97, "Protection of Property within Village Municipality and Municipality Areas")
sub("(1)  Village Municipalities and Municipalities shall look after, maintain and manage: government, community and public property; property constructed, purchased or donated by any institution or person; drains, canals, bridges, ponds, religious sites, rest houses, water mills and public paths; their own buildings, land, parks, gardens and other structures; forests other than national parks, wildlife reserves, wetlands and national forests within their jurisdiction; natural resources beyond the jurisdiction of federal and provincial governments.")
sub("(2)  Village Municipalities and Municipalities shall not sell, transfer or mortgage public and community property.")
sub("(3)  Immovable property in the name of a local authority shall not be sold or transferred without the Government of Nepal's approval.")
