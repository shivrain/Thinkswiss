chapter("CHAPTER 9 — FINANCIAL JURISDICTION OF VILLAGE MUNICIPALITIES AND MUNICIPALITIES")
# ══════════════════════════════════════════════════════════════════════════════
sec(54, "No Tax, Levy or Loan Without Legal Authority")
body("Village Municipalities and Municipalities may not impose or collect any tax or take any loan within their jurisdiction except pursuant to law.")

sec(55, "Property Tax")
sub("(1)  Village Municipalities and Municipalities shall levy property tax on houses and house-land within their areas.")
sub("(2)  Property tax shall be levied on houses and the land they occupy; remaining land and land without houses shall be subject to land tax (malpot) under Section 56.")
note("Explanation: 'Land occupied by a house' means the area of land covered by the house plus up to the same area of additional land.")
sub("(3)  Valuation of houses and house-land for property tax shall be based on: the nature, type, construction and use of the house and land; market value and depreciated value; and commercial or residential use.")
sub("(4)  The rate of property tax shall be based on citizens' standard of living, economic status and capacity to pay.")
sub("(5)  Property tax shall NOT apply to: land and buildings of the Government of Nepal, Provincial Government or local authorities; government hospitals; Guthi-owned property; non-profit educational institutions, companies, committees, authorities, boards and government enterprises; non-profit associations and organisations; religious institutions (temples, monasteries, churches, mosques, etc.); public use sites such as water reservoirs, electricity buildings, cremation grounds, cemeteries, airports, bus parks, stadiums and parks; and embassy and diplomatic mission premises.")

sec(56, "Land Tax (Malpot)")
body("Village Municipalities and Municipalities shall levy land tax (malpot) on land other than that already subject to property tax under Section 55.")

sec(57, "House/Land Rental Tax")
body("Where any person or institution rents out a building, house, shop, garage, warehouse, shed, thatched structure, factory, land or pond — fully or partially — within a local authority's area, the local authority shall levy rental tax on such rental income.")

sec(58, "Business Tax")
body("Village Municipalities and Municipalities shall levy business tax on trade, business or services within their areas based on capital investment and financial turnover.")

sec(59, "Market Stall Fee")
body("Village Municipalities and Municipalities shall levy market stall fees for use of markets, periodic markets or government-land structures constructed, maintained or operated by them.")

sec(60, "Parking Fee")
body("Village Municipalities and Municipalities may levy parking fees for parking services provided within their areas.")

sec(61, "Herb, Scrap and Wildlife Tax")
body("Where any person or institution commercially uses wool, resin, herbs, forest products (khar), scrap materials, or bones/horns/feathers/hides of dead or slaughtered animals (other than those prohibited by law) within a local authority's area, the local authority shall levy herb, scrap and wildlife tax.")

sec(62, "Service Charges")
sub("(1)  Village Municipalities and Municipalities shall levy service charges on cable car, trekking, kayaking, canoeing, bungee jumping, zip-flyer, rafting, paragliding and other local tourism, recreation and adventure sport services or businesses operating within their areas.")
sub("(Proviso)  For services/businesses spanning two or more local authorities (boundary rivers or multi-local), service charges shall be coordinated with relevant local authorities.")
sub("(2)  Service charges may also be levied on drinking water, electricity, taps, rest houses, dharamshalas, libraries, assembly halls; waste management and sanitation; toilets, parks, gyms, hostels, tourism sites; roads, bus parks, drains, bridges, streetlights; property/land valuation services; and recommendation services.")
sub("(3)  Service charge collection may be done by the local authority itself or through management contracts or the private sector.")

sec("62a", "Authority to Sell")
sub("(1)  Local authorities may sell slate, stone, gravel, sand and soil within their areas in quantities determined by environmental impact assessment or initial environmental examination.")
sub("(2)  Local authorities may sell timber, firewood, roots and branches from public and open land within their areas.")
sub("(3)  Revenue from such sales shall be deposited in the local Consolidated Fund.")

sec("62b", "Income from Community Forests")
sub("(1)  Community forest user groups shall prepare annual work plans for forest product sales and use, and have them approved by the local authority.")
sub("(2)  Ten percent of revenue from forest product sales shall be deposited in the relevant local authority's Consolidated Fund.")

sec(63, "Prohibited Taxes/Fees")
sub("(1)  Local authorities may not levy taxes on matters exempt from tax for diplomatic missions or diplomats under prevailing law.")
sub("(2)  Local authorities may not levy any tax or fee on goods imported from abroad for projects of the Government of Nepal, Provincial Government, universities, government hospitals, government-owned institutions or development committees under foreign loans/aid.")
sub("(3)  Integrated property tax shall not apply to unsold stock under collective or joint housing constructed within the local authority's prescribed period; however, if such stock is used in any way, tax shall apply.")
sub("(4)  Integrated property tax shall not apply to basements, gardens, parking and road areas in collective/joint housing approved by the local authority, Nepal Government or Provincial Government that are for collective use.")

sec(65, "Local Revenue Advisory Committee")
sub("(1)  Each local authority shall have a Local Revenue Advisory Committee consisting of: Deputy Mayor/Vice-Chairperson (Convenor); Chief Administrative Officer; two members from Executive including one woman; representatives of private sector industry/commerce organisations; representative of cottage/small industry organisations; and Head of Revenue Division/Department/Branch (Member-Secretary).")
sub("(2)  The committee's functions include: advising on revenue policy and law formulation/amendment; analysing revenue sources, scope and rates; making recommendations on tax policy to promote local industries; advising on tax rates; and other advice for revenue administration reform.")

sec(66, "Resource Estimation and Budget Ceiling Committee")
sub("(1)  Each local authority shall have a Resource Estimation and Budget Ceiling Committee: Chairperson/Mayor (Convenor); Vice-Chairperson/Deputy Mayor; four Executive members including representatives of women, Dalits and minorities (designated by Chairperson/Mayor, including members from other political parties); Chief Administrative Officer (Member-Secretary).")
sub("(2)  The committee shall: project internal revenue, revenue-sharing income, financial transfers, internal borrowing and other revenue; prepare a balanced distribution framework; determine total budget ceilings for the next fiscal year; set thematic budget ceilings; prioritise budget and programmes; and prepare thematic budget formulation guidelines.")
sub("(6)  The committee shall complete its work by Baisakh 10 (mid-April), project an additional two years beyond the upcoming fiscal year, and the Chief Administrative Officer shall provide budget ceilings to thematic departments and ward committees by Baisakh 15.")

sec(67, "Budget and Programme Formulation Committee")
sub("(1)  Each local authority shall have a Budget and Programme Formulation Committee: Deputy Mayor/Vice-Chairperson (Convenor); thematic Executive members; Chief Administrative Officer; Head of Planning Division (Member-Secretary).")
sub("(2)  The committee shall: prepare proposals for next fiscal year's policies and programmes; prioritise budget and programmes within the ceilings; facilitate thematic discussion and prepare final proposals for submission to the Executive; prevent duplication; maintain coherence and complementarity among plans; and perform other necessary functions.")

sec(68, "Authority to Borrow")
sub("(1)  Village Municipalities and Municipalities may borrow internally for productive, employment-generating, revenue-increasing and capital works, within limits recommended by the National Natural Resources and Fiscal Commission, after approval by the Assembly.")
sub("(2)  Such loans shall not exceed twenty-five years.")
sub("(3)  If loans from (or guaranteed by) the Government of Nepal are not repaid within the prescribed period, the Government of Nepal may deduct from grants to that local authority.")
sub("(4)  Other provisions on borrowing shall be pursuant to federal law.")

