#!/usr/bin/env python3
"""
Translate the Local Government Operation Act, 2074 (Nepal) into English
and produce a formatted Word document.
"""

from docx import Document
from docx.shared import Pt, RGBColor, Inches
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn
from docx.oxml import OxmlElement

doc = Document()

for section in doc.sections:
    section.top_margin    = Inches(1.0)
    section.bottom_margin = Inches(1.0)
    section.left_margin   = Inches(1.2)
    section.right_margin  = Inches(1.2)

# ── Helpers ───────────────────────────────────────────────────────────────────
def h1(text):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text); r.bold = True; r.font.size = Pt(15)
    p.paragraph_format.space_before = Pt(12); p.paragraph_format.space_after = Pt(4)

def h2(text):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text); r.bold = True; r.font.size = Pt(12)
    p.paragraph_format.space_before = Pt(8); p.paragraph_format.space_after = Pt(2)

def chapter(text):
    p = doc.add_paragraph()
    r = p.add_run(text); r.bold = True; r.font.size = Pt(11)
    r.font.color.rgb = RGBColor(0,0,0)
    p.paragraph_format.space_before = Pt(14); p.paragraph_format.space_after = Pt(4)
    pPr = p._p.get_or_add_pPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear'); shd.set(qn('w:color'), 'auto'); shd.set(qn('w:fill'), 'EEEEEE')
    pPr.append(shd)

def sec(num, title):
    p = doc.add_paragraph()
    r = p.add_run(f"Section {num}. {title}"); r.bold = True; r.font.size = Pt(10.5)
    p.paragraph_format.space_before = Pt(8); p.paragraph_format.space_after = Pt(2)

def body(text, indent=False):
    p = doc.add_paragraph()
    if indent: p.paragraph_format.left_indent = Inches(0.3)
    r = p.add_run(text); r.font.size = Pt(10); r.font.color.rgb = RGBColor(30,30,30)
    p.paragraph_format.space_before = Pt(1); p.paragraph_format.space_after = Pt(3)

def sub(text):
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Inches(0.3)
    r = p.add_run(text); r.font.size = Pt(10); r.font.color.rgb = RGBColor(30,30,30)
    p.paragraph_format.space_before = Pt(1); p.paragraph_format.space_after = Pt(3)

def clause(letter, text):
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Inches(0.55)
    r = p.add_run(f"({letter})  {text}"); r.font.size = Pt(10); r.font.color.rgb = RGBColor(30,30,30)
    p.paragraph_format.space_before = Pt(1); p.paragraph_format.space_after = Pt(2)

def note(text):
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Inches(0.4)
    r = p.add_run(text); r.font.size = Pt(9.5); r.font.italic = True
    r.font.color.rgb = RGBColor(80,80,80)
    p.paragraph_format.space_before = Pt(1); p.paragraph_format.space_after = Pt(3)

def item(n_or_letter, text, level=1):
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Inches(0.3 * level)
    r = p.add_run(f"({n_or_letter})  {text}"); r.font.size = Pt(10); r.font.color.rgb = RGBColor(30,30,30)
    p.paragraph_format.space_before = Pt(1); p.paragraph_format.space_after = Pt(2)

