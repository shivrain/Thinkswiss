chapter("CHAPTER 10 — FINANCIAL PROCEDURES OF VILLAGE MUNICIPALITIES AND MUNICIPALITIES")
# ══════════════════════════════════════════════════════════════════════════════
sec(69, "Local Consolidated Fund")
sub("(1)  Each Village Municipality and Municipality shall have its own Local Consolidated Fund.")
sub("(2)  The fund shall receive: self-collected revenue; revenue-sharing amounts; Government of Nepal grants; Provincial Government grants; amounts from individuals, associations and institutions; foreign assistance channelled by the Government of Nepal; grants from other local authorities; internal borrowing; and other revenue.")
sub("(3)  All amounts incoming to the fund shall be deposited in a bank account.")
sub("(4)  Expenditure from the fund shall be pursuant to local law.")
sub("(5)  Such law shall allow expenditure from the fund only for: amounts approved in the budget passed by the Assembly; up to one-third of pending budget as advances for daily operations while a budget is under consideration; court-ordered payments; contingency fund contributions approved by the Assembly; and repayment of principal and interest on loans.")

sec(70, "Contingency Fund")
body("Village Municipalities and Municipalities may establish and operate a contingency fund pursuant to local law.")

sec(71, "Budget Presentation and Passage")
sub("(1)  The Vice-Chairperson/Deputy Mayor (or an Executive member designated by the Executive) shall prepare the revenue and expenditure (budget) estimate for the coming fiscal year, have it approved by the Executive, and present it to the Assembly by Ashadh 10 (mid-June).")
sub("(2)  The budget shall include the previous year's actual revenue and expenditure, a revised estimate for the current year, and estimated details of next year's plans, programmes and revenue/expenditure.")
sub("(3)  The Assembly shall complete discussion on the budget within fifteen days.")
sub("(4)  The Assembly may pass the budget or return it to the Executive with suggestions.")
sub("(5)  The Executive shall reconsider and re-present the budget to the Assembly within five days, with or without amendments.")
sub("(6)  The Assembly shall pass the budget by end of Ashadh (mid-July).")
sub("(7)  Newly formed local authorities (first election) shall have two months from taking office to present and pass the budget.")

sec(72, "Fiscal Year and Accounts")
sub("(1)  The fiscal year runs from 1 Shrawan to end of Ashadh (mid-July to mid-July).")
sub("(2)  Local authorities shall follow the revenue/expenditure classification and expenditure heading system determined by the Government of Nepal.")

sec(73, "Expenditure Authority and Procedures")
sub("(1)  Within seven days of budget approval, the Chairperson/Mayor shall grant expenditure authority to the Chief Administrative Officer.")
sub("(2)  Within fifteen days, the Chief Administrative Officer shall distribute expenditure authority with programmes and budgets to division/branch heads and ward secretaries.")
sub("(3)  Those given expenditure authority are fully responsible for expenditure within the approved budget, record-keeping, auditing and clearance of irregularities.")
sub("(4)–(7)  The Consolidated Fund shall be operated by the Chief Administrative Officer and Chief Accountant (for local authorities) or the District Coordination Officer and Chief Accountant (for the District Assembly). Spending shall maintain regularity, economy, efficiency, effectiveness and propriety. The Executive may not spend outside the approved budget headings and ceilings.")

sec(74, "Public Procurement")
sub("(1)  Village Municipalities and Municipalities shall carry out public procurement pursuant to the Federal Public Procurement Act.")
sub("(2)  Within that Act, local authorities may make and implement procurement regulations.")

sec(75, "Transfer to Consolidated Fund")
body("Unspent balances at the end of a fiscal year shall automatically be transferred to the local Consolidated Fund.")

sec(76, "Transaction Accounts")
sub("(1)  Transaction and revenue/expenditure accounting shall be as prescribed.")
