chapter("CHAPTER 7 — BUILDING CONSTRUCTION AND ROADS")
# ══════════════════════════════════════════════════════════════════════════════
sec(27, "Building Construction Without Approved Plans Prohibited")
sub("(1)  No one shall construct a building within a Village Municipality or Municipality without having the plan approved by that local authority.")
sub("(Proviso)  This does not apply to areas and structures designated by the local authority.")
note("Explanation: 'Building construction' includes constructing a new building; demolishing and reconstructing an old building; adding storeys; changing the facade; or adding windows, doors, balconies, verandas, terraces, garages or compound walls — and includes buildings for joint housing.")
sub("(2)  Local authorities shall set land-use standards based on geo-hazard sensitivity and may grant construction approval only in designated areas within such standards.")
sub("(3)  No land may be parcelled or plotted for buildings without prior approval from the local authority.")
sub("(4)  Local authorities may classify buildings in their area and order reconstruction, retrofitting or demolition of buildings at risk from earthquakes or disasters.")
sub("(5)  For areas of historical, cultural, tourism or archaeological significance, local authorities may set standards for building height, setback, roof, facade, materials, colour and aesthetic character.")
sub("(6)  Local authorities may prepare standard sample plans of uniform design for different types and sizes of land and buildings, and provide them free of charge through their technical staff.")

sec(28, "Application for Permission")
sub("(1)  Any person or government office wishing to construct a building within a Village Municipality or Municipality shall submit an application with the building plan in the prescribed format.")
note("Explanation: 'Government office' includes the offices of the President and Vice-President, Supreme Court, Federal Parliament, Provincial Assemblies, constitutional bodies, Nepal Army, Armed Police Force, Nepal Police, Provincial Police and all other government offices and courts.")
sub("(2)  Government agencies that cannot provide a plan for national security reasons may state only the length, width, height, number of storeys and total floor area.")

sec(29, "Contents of the Plan")
body("The plan for a new building shall show the separate septic tank and soak pit, and if the building is to be attached to another building, the plan shall show a separate staircase.")

sec(30, "Submission of Proof of Ownership or Consent")
body("When applying for a building permit, the applicant shall submit proof of ownership of the land, or proof of ownership and written consent if building on another's land. However, land cannot be leased or rented solely to meet plan-pass standards.")

sec(31, "Inquiry")
body("The Chief Administrative Officer shall check the application for completeness within seven days; if complete, shall post a public notice inviting anyone who may be adversely affected to file an objection within fifteen days, and shall deploy an engineer/sub-engineer to inspect whether the construction is feasible.")

sec(32, "Submission of Report")
body("Inspecting staff shall conduct a site inspection, record statements of those present, prepare an inspection report indicating whether construction is permissible or not, and submit it to the local authority within fifteen days of deployment.")

sec(33, "Granting Permission")
sub("(1)  If no objection is received, the Chief Administrative Officer shall grant the building permit within seven days of receiving the inspection report.")
sub("(2)  Otherwise, the permit shall be granted within thirty days, except where a dispute over title requires adjudication.")
sub("(3)  If a dispute over title arises, the parties shall be directed to file a complaint with the District Court within thirty-five days.")
sub("(4)  Fees for building permits shall be as prescribed by the local authority.")

sec(34, "Plan Approval")
sub("(1)  When granting a building permit, the Chief Administrative Officer shall also approve the building plan.")
sub("(2)  The Chief Administrative Officer may approve the plan with necessary additions/alterations to comply with physical development plans and prevailing standards.")

sec(35, "Amendment of Approved Plan")
body("Minor amendments to an approved plan (other than adding storeys, changing the facade, or increasing length/width) may be approved by the Chief Administrative Officer without adverse effect on prevailing standards. Additional storeys, facade changes or dimension increases require a revised plan with additional fees.")

sec(36, "Notice of Refusal")
body("If permission cannot be granted due to the inspection report or other reason, the Chief Administrative Officer shall notify the applicant with reasons within seven days of receiving the report.")

sec(37, "Appeal")
sub("(1)  If permission is not received within the prescribed period, or if the applicant is unsatisfied with the notice, the applicant may appeal to the Chairperson/Mayor within thirty-five days.")
sub("(2)  The Chairperson/Mayor shall inquire and, if construction should be permitted, direct the Chief Administrative Officer to grant permission promptly.")

sec(38, "Period for Building Construction")
sub("(1)  A permit holder shall complete construction within two years of the date of permission.")
sub("(2)–(3)  If unable to complete within two years, the applicant shall apply for an extension before the deadline; the Chief Administrative Officer may extend for two more years on payment of five percent of the original fee.")

sec(39, "Investigation and Action")
sub("(1)  The Chief Administrative Officer may deploy engineers/staff to investigate: whether a building has been constructed or is being constructed with permission pursuant to approved standards; whether it conforms to the approved plan; and whether it encroaches on public land, roads, canals, temples, squares, drains, ponds, etc.")
sub("(2)–(5)  Those constructing buildings shall cooperate with inspectors and provide requested documents. The inspector shall submit a report within fifteen days. If violation is found, the Chairperson/Mayor shall order demolition of the building or relevant part; fines of up to Rs 500,000 for building without plan approval, or up to Rs 200,000 for unapproved alterations.")
sub("(6)  Before ordering demolition, the Chairperson/Mayor shall give the person a reasonable opportunity to be heard.")

sec(40, "Appeal Against Demolition Order")
body("A person aggrieved by a demolition order under Section 39(4) or (5) may appeal to the District Court within thirty-five days; the District Court's decision shall be final.")

sec(41, "Demolition and Cost Recovery")
sub("(1)  If a demolition order under Section 39 is upheld by the District Court, the concerned person shall demolish the building within thirty-five days.")
sub("(2)  If not done within that period, the local authority shall demolish it and recover the cost from the person.")

sec(42, "Special Provision for Plan Approval")
sub("(1)  Buildings constructed before this Act without plan approval or with unapproved alterations — if they comply with building construction standards and codes — may be retroactively approved by the Municipality once, following a prescribed process of 35-day public notice, on-site inspection and collection of triple the normal fee.")
sub("(2)  This provision does not apply to apartments, housing complexes, hotels and other commercial buildings.")

sec(43, "Compliance with National Building Code")
sub("(1)  Village Municipalities and Municipalities shall comply with the National Building Code set by the Government of Nepal when approving building plans.")
sub("(2)  Local authorities may set additional standards within the National Building Code.")

sec(44, "Compliance with National and Provincial Standards")
sub("(1)  Local authorities shall follow national and provincial standards set by the Government of Nepal and Provincial Governments for roads, physical infrastructure, integrated settlement development, urban planning, land-use plans, consumer services and social services.")
sub("(2)  Local authorities may set additional (but not lesser) standards.")

sec(45, "Designation of Road Rights-of-Way")
sub("(1)  Local authorities may designate road right-of-way (ROW) boundaries for local roads.")
sub("(2)–(4)  They shall comply with national and provincial ROW standards; may order removal of any structure within the ROW; and if not removed, may demolish it and recover costs.")
sub("(5)  If ROW boundaries are changed after enactment and someone's land or structure falls within the new ROW, compensation shall be paid when acquiring such land or removing structures.")

